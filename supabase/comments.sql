-- দেশবার্তা: article comments setup
-- news.id হলো bigint, তাই comments.news_id-ও bigint হতে হবে।
-- যদি comments টেবিলটি আগের ভুল SQL দিয়ে তৈরি হয়ে থাকে, এই স্ক্রিপ্ট সেটি মুছে নতুন করে তৈরি করবে।
-- ইতিমধ্যে মন্তব্য থাকলে DROP TABLE চালাবেন না; আগে ব্যাকআপ নিন।
drop table if exists public.comments cascade;
create table public.comments (
 id bigint generated by default as identity primary key,
 news_id bigint not null references public.news(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 display_name text not null,
 body text not null check (char_length(body) between 1 and 1200),
 approved boolean not null default true,
 created_at timestamptz not null default now()
);
alter table public.comments enable row level security;
create policy "Anyone can read approved comments" on public.comments for select using (approved = true);
create policy "Signed-in users can post comments as themselves" on public.comments for insert to authenticated
with check (auth.uid() = user_id and char_length(body) between 1 and 1200);
