-- Supabase SQL Editor-এ চালান। news.id যদি bigint না হয়ে uuid হয়, news_id-এর ধরন uuid করুন।
create table if not exists public.comments (
 id bigint generated by default as identity primary key,
 news_id bigint not null references public.news(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 display_name text not null,
 body text not null check (char_length(body) between 1 and 1200),
 approved boolean not null default true,
 created_at timestamptz not null default now()
);
alter table public.comments enable row level security;
drop policy if exists "Anyone can read approved comments" on public.comments;
create policy "Anyone can read approved comments" on public.comments for select using (approved = true);
drop policy if exists "Signed-in users can post comments as themselves" on public.comments;
create policy "Signed-in users can post comments as themselves" on public.comments for insert to authenticated with check (auth.uid() = user_id and char_length(body) between 1 and 1200);
